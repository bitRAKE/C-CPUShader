from __future__ import annotations

import json
import math
import subprocess
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TOOL = Path(r"msdf-atlas-gen.exe")
FONT = HERE / "NotoSans[wdth,wght].ttf"
ATLAS_PNG = HERE / "ascii_mtsdf.png"
ATLAS_JSON = HERE / "ascii_mtsdf.json"
ATLAS_HEADER = HERE / "ascii_mtsdf_font.h"
ATLAS_RELATIVE_PATH = "pocs/mtsdf/ascii_mtsdf.png"
FONT_NAME = "Noto Sans ASCII Black"
CHARSET_NAME = "ASCII 0x20-0x7E"


def format_float(value: float) -> str:
    if not math.isfinite(value):
        raise ValueError(f"Non-finite float: {value!r}")

    text = f"{value:.9f}".rstrip("0").rstrip(".")
    if text in ("-0", ""):
        text = "0"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text + "f"


def generate_atlas() -> None:
    command = [
        str(TOOL),
        "-varfont",
        f"{FONT}?wght=900&wdth=100",
        "-fontname",
        FONT_NAME,
        "-chars",
        "[0x20, 0x7E]",
        "-type",
        "mtsdf",
        "-overlap",
        "-coloringstrategy",
        "distance",
        "-errordeviationratio",
        "1.15",
        "-size",
        "64",
        "-pxrange",
        "6.1",
        "-outerpxpadding",
        "2",
        "-pots",
        "-yorigin",
        "bottom",
        "-imageout",
        str(ATLAS_PNG),
        "-json",
        str(ATLAS_JSON),
    ]

    subprocess.run(command, check=True, cwd=ROOT)


def emit_header() -> None:
    with ATLAS_JSON.open("r", encoding="utf-8") as handle:
        data = json.load(handle)

    atlas = data["atlas"]
    metrics = data["metrics"]
    glyphs = sorted(data["glyphs"], key=lambda glyph: glyph["unicode"])
    lookup = [-1] * 128

    lines: list[str] = []
    lines.append("/* Generated by pocs/mtsdf/generate_ascii_atlas.py */")
    lines.append("#pragma once")
    lines.append("")
    lines.append('#include "../../src/defines.h"')
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint  unicode;")
    lines.append("    float advance;")
    lines.append("    float plane_left;")
    lines.append("    float plane_bottom;")
    lines.append("    float plane_right;")
    lines.append("    float plane_top;")
    lines.append("    float atlas_left;")
    lines.append("    float atlas_bottom;")
    lines.append("    float atlas_right;")
    lines.append("    float atlas_top;")
    lines.append("    int   has_bounds;")
    lines.append("} mtsdf_ascii_glyph_t;")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    const char *font_name;")
    lines.append("    const char *charset_name;")
    lines.append("    const char *atlas_path;")
    lines.append("    int         atlas_width;")
    lines.append("    int         atlas_height;")
    lines.append("    float       atlas_em_size;")
    lines.append("    float       distance_range;")
    lines.append("    float       distance_range_middle;")
    lines.append("    float       line_height;")
    lines.append("    float       ascender;")
    lines.append("    float       descender;")
    lines.append("    float       underline_y;")
    lines.append("    float       underline_thickness;")
    lines.append("    int         glyph_count;")
    lines.append("    const mtsdf_ascii_glyph_t *glyphs;")
    lines.append("    const short *ascii_lookup;")
    lines.append("} mtsdf_ascii_font_t;")
    lines.append("")
    lines.append(f"enum {{ MTSDF_ASCII_GLYPH_COUNT = {len(glyphs)} }};")
    lines.append("")
    lines.append("static const mtsdf_ascii_glyph_t g_mtsdf_ascii_glyphs[MTSDF_ASCII_GLYPH_COUNT] = {")

    for index, glyph in enumerate(glyphs):
        codepoint = int(glyph["unicode"])
        advance = float(glyph["advance"])
        plane = glyph.get("planeBounds")
        atlas_bounds = glyph.get("atlasBounds")
        has_bounds = plane is not None and atlas_bounds is not None

        plane_left = float(plane["left"]) if has_bounds else 0.0
        plane_bottom = float(plane["bottom"]) if has_bounds else 0.0
        plane_right = float(plane["right"]) if has_bounds else 0.0
        plane_top = float(plane["top"]) if has_bounds else 0.0
        atlas_left = float(atlas_bounds["left"]) if has_bounds else 0.0
        atlas_bottom = float(atlas_bounds["bottom"]) if has_bounds else 0.0
        atlas_right = float(atlas_bounds["right"]) if has_bounds else 0.0
        atlas_top = float(atlas_bounds["top"]) if has_bounds else 0.0

        if 0 <= codepoint < len(lookup):
            lookup[codepoint] = index

        lines.append("    {")
        lines.append(f"        {codepoint}u,")
        lines.append(f"        {format_float(advance)},")
        lines.append(f"        {format_float(plane_left)},")
        lines.append(f"        {format_float(plane_bottom)},")
        lines.append(f"        {format_float(plane_right)},")
        lines.append(f"        {format_float(plane_top)},")
        lines.append(f"        {format_float(atlas_left)},")
        lines.append(f"        {format_float(atlas_bottom)},")
        lines.append(f"        {format_float(atlas_right)},")
        lines.append(f"        {format_float(atlas_top)},")
        lines.append(f"        {1 if has_bounds else 0},")
        lines.append("    },")

    lines.append("};")
    lines.append("")
    lines.append("static const short g_mtsdf_ascii_lookup[128] = {")

    for row in range(0, 128, 16):
        chunk = ", ".join(f"{lookup[row + column]:3d}" for column in range(16))
        lines.append(f"    {chunk},")

    lines.append("};")
    lines.append("")
    lines.append("static const mtsdf_ascii_font_t g_mtsdf_ascii_font = {")
    lines.append(f'    "{FONT_NAME}",')
    lines.append(f'    "{CHARSET_NAME}",')
    lines.append(f'    "{ATLAS_RELATIVE_PATH}",')
    lines.append(f"    {int(atlas['width'])},")
    lines.append(f"    {int(atlas['height'])},")
    lines.append(f"    {format_float(float(atlas['size']))},")
    lines.append(f"    {format_float(float(atlas['distanceRange']))},")
    lines.append(f"    {format_float(float(atlas['distanceRangeMiddle']))},")
    lines.append(f"    {format_float(float(metrics['lineHeight']))},")
    lines.append(f"    {format_float(float(metrics['ascender']))},")
    lines.append(f"    {format_float(float(metrics['descender']))},")
    lines.append(f"    {format_float(float(metrics['underlineY']))},")
    lines.append(f"    {format_float(float(metrics['underlineThickness']))},")
    lines.append("    MTSDF_ASCII_GLYPH_COUNT,")
    lines.append("    g_mtsdf_ascii_glyphs,")
    lines.append("    g_mtsdf_ascii_lookup,")
    lines.append("};")
    lines.append("")

    ATLAS_HEADER.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if not TOOL.exists():
        raise SystemExit(f"msdf-atlas-gen not found: {TOOL}")
    if not FONT.exists():
        raise SystemExit(f"Font not found: {FONT}")

    generate_atlas()
    emit_header()

    print(f"Wrote {ATLAS_PNG}")
    print(f"Wrote {ATLAS_JSON}")
    print(f"Wrote {ATLAS_HEADER}")


if __name__ == "__main__":
    main()
